"""Generate a **separate**, runnable task pool for post-training — never the eval suite.

The eval suite (``tests/evals``) is the held-out benchmark: authored by us, scored by
us, and the one thing that must stay untouched by training so a pass rate still means
something. This module produces the *other* set — the pool the agent is run over to
harvest trajectories from — and it exists because that pool was the single missing link
in the run → record → harvest → train chain: everything downstream of it is built and
was starved for input.

**A generated task is the same on-disk thing an eval task is.** Each one writes a
``task.toml`` + ``fixture/`` + ``solution/`` + ``verify.sh`` in exactly the shape
:mod:`ronin.evals.task` loads and :mod:`ronin.evals.runner` runs, so the pool needs no
second runner, no second loader, and no second verifier — ``scripts/check_eval_tasks.py
--root <pool>`` proves a generated task discriminates by the identical two-way rule it
applies to the suite (bare fixture must fail, solution must pass). Reuse over a parallel
implementation is the whole point: a pool verified by different code than the suite would
drift from it silently.

**Three sources, one contract.** All emit the same shape and every one is
discrimination-guaranteed by construction:

* :func:`eval_style_tasks` — parametric single-file tasks in the suite's own style; the
  fixture is a stub that fails its checks and the solution is the implementation that
  passes them, so the two directions are true by how they are built.
* :func:`bug_injection_tasks` — a known-correct seed module with a *curated* breaking
  mutation applied to make the fixture; the solution is the unmutated seed. The mutation
  list per seed is hand-picked to break at least one assertion, so "the mutant fails and
  the original passes" is not left to chance.
* :func:`mine_prs` — GitHub PRs turned into tasks (issue text → prompt, the PR's added
  tests → ``verify.sh``) through an injected :data:`PullRequestFetcher`. The network is a
  seam so this is tested offline with a recorded fixture; a live miner is opt-in because
  unauthenticated mining is rate-limited and running arbitrary repos' suites is the slow,
  flaky part — the deterministic sources above are what a green pool is built from.

**Reproducible verification is a container's job, and the command is built here.**
:func:`container_command` renders the exact ``docker run`` argv that runs a task's
``verify.sh`` in a clean image with the network off — the reproducibility the pool needs
before its pass/fail signal can be trusted as a reward. It is a pure function returning
argv (unit-tested for shape) rather than a live call, so it is correct and reviewable
without a daemon; the offline discrimination check runs ``verify.sh`` under ``bash``,
which is the same script the container would run.

**The pool is never the eval suite, and the writer enforces it.** :func:`write_pool`
refuses any output directory at or under ``tests/evals`` (:data:`EVAL_SUITE_MARKER`),
because a pool written there would become training input to the one suite that must never
be trained on — the exact contamination this module exists to prevent.

Everything is deterministic: a seed in, a byte-identical pool out. Content-hash dedup
(:meth:`GeneratedTask.content_hash`) means a larger ``--count`` never produces a duplicate
task, and a regenerated pool is diffable.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import sys
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, replace
from pathlib import Path
from typing import Final

#: A path component that means "this is the held-out benchmark". The writer refuses to
#: emit into any directory whose parts contain both of these in order.
EVAL_SUITE_MARKER: Final[tuple[str, str]] = ("tests", "evals")

#: Default image for the reproducible container run. Slim and stdlib-only, because every
#: generated ``verify.sh`` is written to need nothing but ``bash`` and CPython.
DEFAULT_IMAGE: Final[str] = "python:3.11-slim"

#: How many aligned attempts :func:`generate_pool` makes past ``count`` before it accepts
#: that the parameter space is exhausted, mirroring ``synthetic_corpus`` so a caller who
#: asks for more unique tasks than exist gets fewer, never a hang.
_ATTEMPT_FACTOR: Final[int] = 60

_VERIFY_HEADER: Final[str] = (
    "#!/usr/bin/env bash\n"
    "# Generated by ronin.evals.poolgen. Runs inside the task workspace after the agent\n"
    "# finishes; exit 0 == solved. Stdlib python + POSIX shell only: no network, no clock,\n"
    "# no randomness, so the same workspace scores the same in bash or in a container.\n"
    "set -uo pipefail\n"
    'PY="${RONIN_EVAL_PYTHON:-python3}"\n'
)


@dataclass(frozen=True, slots=True)
class GeneratedTask:
    """One runnable task, in the eval suite's on-disk shape.

    ``fixture`` and ``solution`` are ``{relative_path: file_text}`` maps. ``verify`` is the
    whole ``verify.sh`` body. ``source`` records which generator made it, so a harvest can
    weight or filter by provenance without re-deriving it.
    """

    task_id: str
    category: str
    prompt: str
    fixture: Mapping[str, str]
    solution: Mapping[str, str]
    verify: str
    source: str
    files_expected: tuple[str, ...] = ()
    tags: tuple[str, ...] = ()
    max_turns: int = 12

    def __post_init__(self) -> None:
        if "/" not in self.task_id:
            raise ValueError(f"task_id must be 'category/slug', got {self.task_id!r}")
        if not self.fixture:
            raise ValueError(f"{self.task_id}: a task needs a fixture the agent starts from")
        if not self.solution:
            raise ValueError(f"{self.task_id}: a task needs a reference solution to prove it")

    def content_hash(self) -> str:
        """A stable digest over everything that makes this task what it is.

        Used for dedup, so two tasks that differ only in id (same fixture, solution and
        checks) collapse to one — a pool full of the same task with different names would
        inflate the count and teach nothing new.
        """
        payload = json.dumps(
            {
                "category": self.category,
                "prompt": self.prompt,
                "fixture": dict(sorted(self.fixture.items())),
                "solution": dict(sorted(self.solution.items())),
                "verify": self.verify,
            },
            sort_keys=True,
            ensure_ascii=False,
        )
        return hashlib.blake2b(payload.encode("utf-8"), digest_size=16).hexdigest()

    def toml(self) -> str:
        """The ``task.toml`` a suite loader reads. Minimal, valid, and pool-marked."""
        expected = ", ".join(f'"{path}"' for path in self.files_expected)
        tags = ", ".join(f'"{tag}"' for tag in self.tags)
        return (
            f'id = "{self.task_id}"\n'
            f'category = "{self.category}"\n'
            f"prompt = {_toml_string(self.prompt)}\n"
            f'fixture = "fixture"\n'
            'git_url = ""\n'
            'git_sha = ""\n'
            f"files_expected = [{expected}]\n"
            f"max_turns = {self.max_turns}\n"
            f"timeout_seconds = 120\n"
            f"tags = [{tags}]\n"
            # A pool task is never a regression-gate task: the gate is the suite's alone.
            "regression_gate = false\n"
            f'source = "{self.source}"\n'
        )

    def write(self, pool_root: Path) -> Path:
        """Write this task's directory under ``pool_root`` and return it."""
        directory = pool_root / self.task_id
        (directory / "fixture").mkdir(parents=True, exist_ok=True)
        (directory / "solution").mkdir(parents=True, exist_ok=True)
        (directory / "task.toml").write_text(self.toml(), encoding="utf-8")
        for name, text in self.fixture.items():
            target = directory / "fixture" / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
        for name, text in self.solution.items():
            target = directory / "solution" / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
        verify = directory / "verify.sh"
        verify.write_text(self.verify, encoding="utf-8", newline="\n")
        verify.chmod(0o755)
        return directory


def _toml_string(text: str) -> str:
    """A TOML string literal for ``text`` — a triple-quoted block when it has newlines."""
    if "\n" in text:
        body = text if text.endswith("\n") else text + "\n"
        return '"""\n' + body + '"""'
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


# --------------------------------------------------------------------------- #
# verify.sh: a stdlib-python assertion harness, so no pytest is needed in a workspace
# --------------------------------------------------------------------------- #


def _verify_script(check_body: str) -> str:
    """Wrap a python assertion body in the generated ``verify.sh`` contract.

    ``check_body`` imports the task's module and asserts its behaviour. A raised
    ``AssertionError`` (bare fixture) makes python exit non-zero; a clean run (solution)
    exits 0 — which is exactly the two-way discrimination the pool is checked against.
    """
    indented = "\n".join(check_body.strip("\n").splitlines())
    return (
        _VERIFY_HEADER
        + "\"$PY\" - <<'PYCHECK'\n"
        + indented
        + "\nPYCHECK\n"
        + '[ $? -eq 0 ] || { echo "FAIL: behaviour did not match the task" >&2; exit 1; }\n'
        + "exit 0\n"
    )



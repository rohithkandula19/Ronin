# Source 1 — eval-style parametric tasks
# --------------------------------------------------------------------------- #

#: One eval-style family: a stub fixture that fails, a solution that passes, and a check
#: body parameterised by a per-task ``dict`` the family draws from an rng.
EvalFamily = Callable[[random.Random], "GeneratedTask"]


def _fam_dedupe(rng: random.Random) -> GeneratedTask:
    pool = [
        f"{p}-{i:02d}" for p in ("web", "db", "api", "edge", "cache", "store") for i in range(20)
    ]
    picks = rng.sample(pool, rng.randint(4, 8))
    seq = [*picks, *rng.sample(picks, rng.randint(1, len(picks)))]
    rng.shuffle(seq)
    want: list[str] = []
    for host in seq:
        if host not in want:
            want.append(host)
    slug = f"dedupe-{rng.randrange(1_000_000):06d}"
    stub = "def unique_hosts(hosts):\n    raise NotImplementedError\n"
    sol = (
        "def unique_hosts(hosts):\n"
        "    seen = {}\n"
        "    for h in hosts:\n"
        "        seen[h] = None\n"
        "    return list(seen)\n"
    )
    check = (
        "from collect import unique_hosts\n"
        f"seq = {seq!r}\n"
        f"assert unique_hosts(list(seq)) == {want!r}\n"
        "assert unique_hosts([]) == []\n"
    )
    return GeneratedTask(
        task_id=f"single-file/{slug}",
        category="single-file",
        prompt="`collect.py`'s `unique_hosts` is unimplemented. Remove duplicates while "
        "keeping the first occurrence of each host in input order. Keep the signature.",
        fixture={"collect.py": stub},
        solution={"collect.py": sol},
        verify=_verify_script(check),
        source="eval-style",
        files_expected=("collect.py",),
        tags=("python", "order"),
    )


def _fam_clamp(rng: random.Random) -> GeneratedTask:
    lo, hi = sorted((rng.randint(-50, 0), rng.randint(1, 50)))
    points = [rng.randint(lo - 20, hi + 20) for _ in range(6)]
    want = [min(max(p, lo), hi) for p in points]
    slug = f"clamp-{rng.randrange(1_000_000):06d}"
    stub = "def clamp(value, lo, hi):\n    return value\n"
    sol = "def clamp(value, lo, hi):\n    return min(max(value, lo), hi)\n"
    check = (
        "from box import clamp\n"
        f"pts = {points!r}\n"
        f"assert [clamp(p, {lo}, {hi}) for p in pts] == {want!r}\n"
        f"assert clamp({hi} + 5, {lo}, {hi}) == {hi}\n"
        f"assert clamp({lo} - 5, {lo}, {hi}) == {lo}\n"
    )
    return GeneratedTask(
        task_id=f"single-file/{slug}",
        category="single-file",
        prompt="`box.py`'s `clamp` ignores its bounds. Return `value` limited to the "
        "inclusive range [lo, hi]. Keep the signature.",
        fixture={"box.py": stub},
        solution={"box.py": sol},
        verify=_verify_script(check),
        source="eval-style",
        files_expected=("box.py",),
        tags=("python", "bounds"),
    )


def _fam_safe_divide(rng: random.Random) -> GeneratedTask:
    nums = [rng.randint(-30, 30) for _ in range(5)]
    dens = [rng.choice([0, rng.randint(1, 9), 0, rng.randint(-9, -1)]) for _ in range(5)]
    want = [(n / d if d else 0.0) for n, d in zip(nums, dens, strict=True)]
    slug = f"safe-divide-{rng.randrange(1_000_000):06d}"
    stub = "def safe_divide(n, d):\n    return n / d\n"
    sol = "def safe_divide(n, d):\n    return n / d if d else 0.0\n"
    check = (
        "from ratio import safe_divide\n"
        f"pairs = {list(zip(nums, dens, strict=True))!r}\n"
        f"assert [safe_divide(n, d) for n, d in pairs] == {want!r}\n"
        "assert safe_divide(1, 0) == 0.0\n"
    )
    return GeneratedTask(
        task_id=f"single-file/{slug}",
        category="single-file",
        prompt="`ratio.py`'s `safe_divide` raises on a zero denominator. Return 0.0 when "
        "`d` is zero, otherwise `n / d`. Keep the signature.",
        fixture={"ratio.py": stub},
        solution={"ratio.py": sol},
        verify=_verify_script(check),
        source="eval-style",
        files_expected=("ratio.py",),
        tags=("python", "edge-case"),
    )


_EVAL_FAMILIES: Final[tuple[EvalFamily, ...]] = (_fam_dedupe, _fam_clamp, _fam_safe_divide)


def eval_style_tasks(rng: random.Random, count: int) -> list[GeneratedTask]:
    """``count`` parametric single-file tasks, cycling the families for balance."""
    tasks: list[GeneratedTask] = []
    for index in range(count):
        family = _EVAL_FAMILIES[index % len(_EVAL_FAMILIES)]
        tasks.append(family(rng))
    return tasks


# --------------------------------------------------------------------------- #
# Source 2 — synthetic bug injection over known-correct seed modules
# --------------------------------------------------------------------------- #


@dataclass(frozen=True, slots=True)
class Seed:
    """A known-correct module, the checks that prove it, and curated breaking mutations.

    Each ``(find, replace)`` mutation is hand-picked to break at least one assertion in
    ``check``, so injecting it and then running ``verify.sh`` fails on the mutant and
    passes on the unmutated seed — discrimination by construction, never by luck.
    """

    module: str
    filename: str
    source_text: str
    prompt: str
    check: str
    mutations: tuple[tuple[str, str], ...]


_SEEDS: Final[tuple[Seed, ...]] = (
    Seed(
        module="stats",
        filename="stats.py",
        source_text=(
            "def running_max(values):\n"
            "    best = None\n"
            "    out = []\n"
            "    for v in values:\n"
            "        if best is None or v > best:\n"
            "            best = v\n"
            "        out.append(best)\n"
            "    return out\n"
        ),
        prompt="`stats.py`'s tests fail after a change. `running_max` must return the "
        "running maximum so far at each index. Fix it so the tests pass again.",
        check=(
            "from stats import running_max\n"
            "assert running_max([1, 3, 2, 5, 4]) == [1, 3, 3, 5, 5]\n"
            "assert running_max([5, 1, 1]) == [5, 5, 5]\n"
            # A negative-only case, so the `best = 0` mutation (which matches the
            # original on all-positive data) is actually caught.
            "assert running_max([-5, -2, -9, -1]) == [-5, -2, -2, -1]\n"
            "assert running_max([]) == []\n"
        ),
        mutations=(
            ("v > best", "v < best"),
            ("best = None", "best = 0"),
            ("out.append(best)", "out.append(v)"),
        ),
    ),
    Seed(
        module="pager",
        filename="pager.py",
        source_text=(
            "def page_count(total, size):\n"
            "    if size <= 0:\n"
            "        raise ValueError('size must be positive')\n"
            "    return -(-total // size)\n"
        ),
        prompt="`pager.py`'s tests fail. `page_count` must return the number of pages of "
        "`size` needed for `total` items (the last page may be partial). Fix it.",
        check=(
            "from pager import page_count\n"
            "assert page_count(10, 3) == 4\n"
            "assert page_count(9, 3) == 3\n"
            "assert page_count(0, 3) == 0\n"
            "assert page_count(1, 10) == 1\n"
        ),
        mutations=(
            ("-(-total // size)", "total // size"),
            ("-(-total // size)", "total // size + 1"),
        ),
    ),
    Seed(
        module="text",
        filename="text.py",
        source_text=("def normalise(name):\n    return ' '.join(name.split()).strip().lower()\n"),
        prompt="`text.py`'s tests fail. `normalise` must collapse runs of whitespace to a "
        "single space, strip the ends, and lowercase. Fix it.",
        check=(
            "from text import normalise\n"
            "assert normalise('  Foo   Bar ') == 'foo bar'\n"
            "assert normalise('BAZ') == 'baz'\n"
            "assert normalise('a\\tb') == 'a b'\n"
        ),
        mutations=(
            (".lower()", ".upper()"),
            ("' '.join(name.split())", "name"),
        ),
    ),
)


def bug_injection_tasks(rng: random.Random, count: int) -> list[GeneratedTask]:
    """``count`` bug-fix tasks: a seed module broken by a curated mutation.

    The full ``(seed, mutation)`` product is enumerated deterministically and shuffled by
    ``rng``, so a given seed produces reproducible tasks and the requested ``count`` is
    filled from the front. Capacity is the product size; asking for more returns all of
    them.
    """
    catalogue: list[GeneratedTask] = []
    for seed in _SEEDS:
        for index, (find, substitute) in enumerate(seed.mutations):
            if find not in seed.source_text:  # pragma: no cover - guards a bad mutation
                raise ValueError(f"{seed.module}: mutation {find!r} not present in the seed")
            broken = seed.source_text.replace(find, substitute, 1)
            slug = f"{seed.module}-fix-{index:02d}"
            catalogue.append(
                GeneratedTask(
                    task_id=f"bug-from-trace/{slug}",
                    category="bug-from-trace",
                    prompt=seed.prompt,
                    fixture={seed.filename: broken},
                    solution={seed.filename: seed.source_text},
                    verify=_verify_script(seed.check),
                    source="bug-injection",
                    files_expected=(seed.filename,),
                    tags=("python", "bugfix"),
                    max_turns=14,
                )
            )
    rng.shuffle(catalogue)
    return catalogue[:count]


# --------------------------------------------------------------------------- #
# Source 3 — GitHub PR mining (network behind a seam; live is opt-in)
# --------------------------------------------------------------------------- #


@dataclass(frozen=True, slots=True)
class MinedPR:
    """The raw material one merged PR contributes: an issue, a test file, and a fix.

    ``test_files`` become ``verify.sh`` inputs and land in the fixture; ``fix_files`` land
    in the solution. Keeping them separate is what lets the bare fixture (tests, no fix)
    fail and the solution (tests + fix) pass — the same two-way rule as every other source.
    """

    repo: str
    number: int
    issue_title: str
    issue_body: str
    test_files: Mapping[str, str]
    fix_files: Mapping[str, str]


#: The network seam. A real fetcher hits the GitHub API; the tests pass a recorded list.
PullRequestFetcher = Callable[[str, int], Sequence[MinedPR]]


def mine_prs(fetcher: PullRequestFetcher, *, repo: str, limit: int) -> list[GeneratedTask]:
    """Turn merged PRs into tasks: issue text → prompt, the PR's tests → ``verify.sh``.

    Only PRs that carry both a test file and a fix file become tasks — a PR with no test
    cannot be verified, and one with no fix has no reference solution, so neither can
    discriminate and both are dropped rather than emitted as a task that always scores the
    same. The ``fetcher`` is injected so the whole path is offline in tests; wiring a live
    GitHub fetcher is a deliberate, rate-limited follow-up (see the module docstring).
    """
    tasks: list[GeneratedTask] = []
    for pr in fetcher(repo, limit):
        if not pr.test_files or not pr.fix_files:
            continue
        first_test = sorted(pr.test_files)[0]
        slug = f"{pr.repo.replace('/', '-')}-{pr.number}"
        check = (
            "import subprocess, sys\n"
            f"proc = subprocess.run([sys.executable, '-m', 'pytest', '-q', {first_test!r}])\n"
            "assert proc.returncode == 0, 'the PR tests still fail'\n"
        )
        prompt = pr.issue_title.strip()
        if pr.issue_body.strip():
            prompt = f"{prompt}\n\n{pr.issue_body.strip()}"
        tasks.append(
            GeneratedTask(
                task_id=f"pr-mined/{slug}",
                category="multi-file",
                prompt=prompt,
                fixture={**pr.test_files},
                solution={**pr.fix_files},
                verify=_verify_script(check),
                source="pr-mined",
                files_expected=tuple(sorted(pr.fix_files)),
                tags=("python", "from-pr"),
                max_turns=20,
            )
        )
    return tasks


# --------------------------------------------------------------------------- #
# Assembling and writing a pool
# --------------------------------------------------------------------------- #


def generate_pool(count: int, *, seed: int = 0) -> list[GeneratedTask]:
    """``count`` unique tasks, deterministic for ``seed``, deduped by content.

    Draws from the two offline sources (eval-style and bug-injection) in a stable
    interleave. PR-mined tasks are not included here because they need a fetcher; a caller
    with one folds :func:`mine_prs` output into the pool itself.
    """
    if count < 1:
        raise ValueError("count must be >= 1")
    rng = random.Random(seed)
    tasks: dict[str, GeneratedTask] = {}
    injected = bug_injection_tasks(rng, count)  # capped at capacity, shuffled by rng
    for task in injected:
        tasks[task.content_hash()] = task
    attempts = 0
    limit = count * _ATTEMPT_FACTOR
    while len(tasks) < count and attempts < limit:
        attempts += 1
        for task in eval_style_tasks(rng, 1):
            tasks.setdefault(task.content_hash(), task)
            if len(tasks) >= count:
                break
    # Re-id from the content hash so an id is unique by construction: eval-style slugs
    # carry a random suffix the content hash deliberately ignores, so two distinct tasks
    # could otherwise share an id and overwrite each other on disk. Same content → same
    # id (stable, diffable); different content → different id (never a collision).
    reided: list[GeneratedTask] = []
    for task in tasks.values():
        stem = task.task_id.split("/", 1)[1].rsplit("-", 1)[0]
        reided.append(replace(task, task_id=f"{task.category}/{stem}-{task.content_hash()[:10]}"))
    ordered = sorted(reided, key=lambda t: t.task_id)
    return ordered[:count]


def _is_eval_suite(path: Path) -> bool:
    parts = tuple(path.resolve().parts)
    marker = EVAL_SUITE_MARKER
    return any(parts[i : i + len(marker)] == marker for i in range(len(parts)))


def write_pool(
    tasks: Sequence[GeneratedTask], out: Path, *, allow_eval_suite: bool = False
) -> Path:
    """Write every task under ``out`` and a ``manifest.toml``. Refuses the eval suite.

    ``allow_eval_suite`` exists only so a test can prove the guard fires; nothing in the
    product ever sets it. Writing a training pool into ``tests/evals`` would make the
    held-out benchmark trainable, which is the one thing this module must not allow.
    """
    if not allow_eval_suite and _is_eval_suite(out):
        raise ValueError(
            f"refusing to write a task pool into the eval suite ({out}): the pool is "
            "training input and the suite must never be trained on"
        )
    out.mkdir(parents=True, exist_ok=True)
    for task in tasks:
        task.write(out)
    ids = ", ".join(f'"{task.task_id}"' for task in tasks)
    (out / "manifest.toml").write_text(
        "# Generated task pool — NOT the eval suite. Never training-gate or benchmark on it.\n"
        f"total = {len(tasks)}\n"
        f"tasks = [{ids}]\n",
        encoding="utf-8",
    )
    return out


def container_command(
    task_dir: Path,
    *,
    image: str = DEFAULT_IMAGE,
    verify_name: str = "verify.sh",
    network: bool = False,
) -> list[str]:
    """The ``docker run`` argv that runs a task's ``verify.sh`` reproducibly.

    Pure: it builds the command, it does not run it, so the container contract is
    reviewable and unit-testable with no daemon. ``--network none`` by default because a
    verify that reaches the network is not reproducible; the workspace is mounted
    read-write at ``/task`` and the script runs with that as the cwd, exactly as the
    offline ``bash`` path runs it.
    """
    return [
        "docker",
        "run",
        "--rm",
        f"--network={'bridge' if network else 'none'}",
        "-v",
        f"{task_dir.resolve()}:/task:rw",
        "-w",
        "/task",
        image,
        "bash",
        verify_name,
    ]


def main(argv: Sequence[str] | None = None) -> int:
    """``python -m ronin.evals.poolgen --out pool --count 800`` — write a pool."""
    parser = argparse.ArgumentParser(prog="ronin.evals.poolgen", description=__doc__)
    parser.add_argument("--out", type=Path, required=True, help="pool directory to write")
    parser.add_argument("--count", type=int, default=800, help="how many tasks (800-1500)")
    parser.add_argument("--seed", type=int, default=0, help="deterministic seed")
    args = parser.parse_args(list(argv) if argv is not None else None)
    try:
        tasks = generate_pool(args.count, seed=args.seed)
        write_pool(tasks, args.out)
    except ValueError as exc:
        print(f"poolgen: {exc}", file=sys.stderr)
        return 1
    by_source: dict[str, int] = {}
    for task in tasks:
        by_source[task.source] = by_source.get(task.source, 0) + 1
    print(f"wrote {len(tasks)} task(s) to {args.out}")
    for source, n in sorted(by_source.items()):
        print(f"  {source:>14}: {n}")
    print("verify each: scripts/check_eval_tasks.py --root", args.out)
    return 0



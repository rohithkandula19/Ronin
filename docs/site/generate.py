HOOKS_INTRO = f"""
Generated from `ronin.agents.hooks`. A hook is a shell command the session runs when
something happens. It gets the event as JSON on stdin, and what it does with its exit
code is the whole feature.

The exit-code contract is the part people get wrong, so it is stated first:

* **exit 0** — fine. Anything on stdout is context the model can be shown.
* **exit {BLOCK_EXIT_CODE}** — *block*. The action does not happen and stderr becomes
  the reason the model is told. This is the load-bearing case: it is how a team
  enforces "never touch `migrations/`" without patching Ronin.
* **any other non-zero** — a warning. The action proceeds. A hook that exits 1 because
  `prettier` is not installed must not stop the agent from working; if every failure
  blocked, one broken hook would wedge every session, and the first thing a user does
  with a wedged agent is delete all their hooks.

A timeout is a warning too, for the same reason — with one opt-in exception,
`block_on_timeout`, for the hook whose whole purpose is to refuse.
"""



# --------------------------------------------------------------------------- #
# Rendering helpers
# --------------------------------------------------------------------------- #


def _page(title: str, intro: str, body: Sequence[str]) -> str:
    """One page: marker, H1, intro paragraph, then body lines. Trailing newline."""
    lines = [MARKER, "", f"# {title}", "", intro.strip(), "", *body]
    text = "\n".join(lines).rstrip("\n")
    return text + "\n"


def _table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    out.extend("| " + " | ".join(cell for cell in row) + " |" for row in rows)
    return out


def _cell(text: str) -> str:
    """Make a string safe inside a markdown table cell, deterministically."""
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _schema_lines(spec: ToolSpec) -> list[str]:
    """One line per argument, from the tool's real JSON Schema."""
    schema = spec.json_schema
    properties = schema.get("properties")
    if not isinstance(properties, Mapping) or not properties:
        return ["_takes no arguments._"]
    required = schema.get("required")
    required_names = set(required) if isinstance(required, list) else set()
    rows: list[list[str]] = []
    for name in properties:
        entry = properties[name]
        detail = entry if isinstance(entry, Mapping) else {}
        kind = str(detail.get("type", "any"))
        note = str(detail.get("description", ""))
        rows.append(
            [
                f"`{name}`",
                kind,
                "yes" if name in required_names else "no",
                _cell(note),
            ]
        )
    return _table(("argument", "type", "required", "meaning"), rows)



async def _no_fetch(url: str) -> tuple[str, str]:
    """Stand-in fetcher. Never called: the generator only reads specs."""
    raise NotImplementedError(url)


async def _no_extract(html: str, url: str) -> str:
    raise NotImplementedError(url)


async def _no_search(query: str) -> Sequence[Mapping[str, str]]:
    raise NotImplementedError(query)


def _no_subagent(prompt: str, subagent: SubagentType) -> Awaitable[str]:
    raise NotImplementedError(subagent.name)


def full_registry(root: Path) -> ToolRegistry:
    """Every tool a session can have, assembled without touching anything.

    ``build_registry`` gates each tool group behind a dependency, so documenting the
    full set means supplying one of each. None of them is ever invoked here — the page
    is rendered from ``ToolSpec``s — and ``PersistentShell`` does not spawn ``bash``
    until ``start()``, so this stays a pure in-memory construction.
    """
    ctx = ToolContext(root=root, env={})
    return build_registry(
        ctx,
        shell=ShellSession(shell=PersistentShell(cwd=root, env={})),
        subagent_runner=_no_subagent,
        fetch=_no_fetch,
        extract=_no_extract,
        search=_no_search,
        clock=lambda: 0.0,
    )


def cli_registry(root: Path) -> ToolRegistry:
    """The tools a plain ``python -m ronin`` session gets, derived the same way it is.

    ``ronin.cli.wire.build_runtime`` wires a shell and — *unconditionally* — a fetcher and
    extractor, so ``web_fetch`` is in every CLI session; ``ronin.session.build_session``
    then adds ``task``. ``web_search`` is deliberately absent here: ``build_runtime`` adds
    it only when a search provider is configured (``RONIN_SEARCH_PROVIDER``), which a bare
    session has not set, so a bare CLI session has no ``web_search``. Mirroring
    ``build_runtime`` here rather than hardcoding a list is what keeps the "in a plain
    session?" column true after someone changes the wiring. None of these callables is
    invoked — the page is rendered from ``ToolSpec``s — so the ``_no_*`` sentinels are safe.
    """
    ctx = ToolContext(root=root, env={})
    return build_registry(
        ctx,
        shell=ShellSession(shell=PersistentShell(cwd=root, env={})),
        fetch=_no_fetch,
        extract=_no_extract,
        clock=lambda: 0.0,
    )


#: Added by ``ronin.session.build_session`` after ``build_registry`` returns, because
#: ``TaskTool`` needs a runner that needs a registry that contains ``TaskTool``.

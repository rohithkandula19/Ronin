def render_all() -> dict[str, str]:
    """Every generated page, keyed by filename. The one source of truth for staleness."""
    rendered = {
        "tools.md": render_tools(),
        "config.md": render_config(),
        "hooks.md": render_hooks(),
        "subagents.md": render_subagents(),
        "providers.md": render_providers(),
        "telemetry.md": render_telemetry(),
    }
    missing = set(GENERATED_PAGES) - set(rendered)
    extra = set(rendered) - set(GENERATED_PAGES)
    if missing or extra:
        raise SystemExit(
            f"GENERATED_PAGES disagrees with render_all(): missing {sorted(missing)}, "
            f"unexpected {sorted(extra)}"
        )
    return rendered


def stale(directory: Path | None = None) -> list[str]:
    """Filenames whose contents on disk differ from what the code now renders."""
    target = SITE if directory is None else directory
    out: list[str] = []
    for name, body in render_all().items():
        path = target / name
        # Bytes, not text: read_text applies universal-newline translation and would
        # hide a CRLF regression in a file this script writes with newline="\n".
        current = path.read_bytes() if path.exists() else b""
        if current != body.encode("utf-8"):
            out.append(name)
    return out


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="generate docs/site reference pages")
    parser.add_argument("--check", action="store_true", help="exit 1 if any page is stale")
    args = parser.parse_args(list(argv) if argv is not None else None)

    drifted = stale()
    if args.check:
        if drifted:
            sys.stderr.write(
                "docs/site pages are STALE: "
                + ", ".join(sorted(drifted))
                + "\nrun: python docs/site/generate.py\n"
            )
            return 1
        print(f"docs/site: {len(GENERATED_PAGES)} generated page(s) up to date")
        return 0

    for name, body in render_all().items():
        (SITE / name).write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {len(GENERATED_PAGES)} page(s) to {SITE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

TOOLS_INTRO = """
Every tool a session can hold, generated from `ronin.tools.registry.build_registry`.
The description text below each heading is the *exact* string sent to the model —
`Tool.describe()` renders it, in a fixed order (summary, when to use, when not to
use, worked examples), because a description that only says what a tool does gets
called in situations it should not be.

A session does not necessarily have all of these. `build_registry` gates each group
behind a dependency: no shell means no `bash`, no fetcher means no `web_fetch`. A
tool that is absent is invisible to the model, which is strictly better than one that
exists and always errors. `--mode plan` narrows the set further, to read-only tools
only, and re-derives that property from the specs rather than trusting a prompt.

`danger level` decides what the permission gate does with a call: `read_only` never
asks, and anything higher can be gated by a rule in `.ronin/settings.json`. See
[config.md](config.md).
"""


def render_tools() -> str:
    registry = full_registry(ROOT)
    specs = sorted(registry.specs(), key=lambda spec: spec.name)
    in_cli = {spec.name for spec in cli_registry(ROOT).specs()} | set(SESSION_ADDED_TOOLS)
    needs_injection = [spec.name for spec in specs if spec.name not in in_cli]
    body: list[str] = [
        f"{len(specs)} tools, listed alphabetically.",
        "",
        *_table(
            ("tool", "danger level", "approval by default", "in a plain session?"),
            [
                [
                    f"[`{spec.name}`](#{spec.name})",
                    spec.danger_level.name.lower(),
                    "yes" if spec.requires_approval else "no",
                    "yes" if spec.name in in_cli else "no — needs a search provider",
                ]
                for spec in specs
            ],
        ),
        "",
        "The last column is derived, not asserted: `ronin.cli.wire.build_runtime` wires "
        "the shell and — unconditionally — a fetcher and extractor, so `web_fetch` is "
        "present in every CLI session; `ronin.session.build_session` then adds "
        + ", ".join(f"`{name}`" for name in SESSION_ADDED_TOOLS)
        + ". "
        + (
            ", ".join(f"`{name}`" for name in needs_injection)
            + " is the one tool a bare `python -m ronin` session does **not** have: it "
            "appears only when a search provider is configured (`RONIN_SEARCH_PROVIDER`), "
            "because a search tool with no backend that errors on every call teaches the "
            "model to keep trying it"
            if needs_injection
            else "every tool below is present in a `python -m ronin` session"
        )
        + ". Web content that does arrive — from `web_fetch` or `web_search` — is "
        "registered with the taint tracker and surfaced as untrusted data, not obeyed as "
        "instructions; see [config.md](config.md).",
        "",
    ]
    for spec in specs:
        body.extend(
            [
                f"## {spec.name}",
                "",
                f"`danger_level` `{spec.danger_level.name.lower()}` "
                f"({int(spec.danger_level)} of {int(max(DangerLevel))}) · "
                f"`requires_approval` `{str(spec.requires_approval).lower()}`",
                "",
                "### arguments",
                "",
                *_schema_lines(spec),
                "",
                "### description, as the model receives it",
                "",
                "```text",
                *spec.description.splitlines(),
                "```",
                "",
            ]
        )
    return _page("tool reference", TOOLS_INTRO, body)



#!/usr/bin/env python3
"""Generate the reference pages of ``docs/site/`` from the code they document.

Hand-written reference documentation drifts the day it is written. Every page this
script owns is derived from the real objects — the tool registry, the settings
loader, the hook events, the subagent definitions, the provider adapter table — so a
page cannot disagree with the code without a test going red.

The pattern is copied from ``scripts/sync_typecheck_paths.py`` and
``scripts/generate_readme_stats.py``: write in place by default, ``--check`` to fail
when a file on disk differs from what the code now says::

    python docs/site/generate.py           # rewrite the generated pages
    python docs/site/generate.py --check   # exit 1 if any page is stale

``tests/telemetry/test_ronin_telemetry_docsite.py`` runs the same comparison, so the
staleness gate holds even where this script is not wired into CI.

**Only reference pages are generated.** ``index.md`` and ``quickstart.md`` are prose
about how to use the thing, which no amount of introspection produces; they are
hand-written and carry no generated marker. Every generated page carries
:data:`MARKER` on its first line so nobody edits one by hand and loses the edit.

There is no static-site generator here on purpose: the repository has none already
(no mkdocs, no sphinx, no docusaurus), and adding one to render seven markdown files
would be a build dependency in exchange for a nav bar. Plain markdown renders on
GitHub, in an editor, and in every static host, and it is what the rest of ``docs/``
already is.

No measured numbers appear on any page. Counts that are derived by walking a real
object — "13 tools", "5 hook events" — are facts about this checkout and are
recomputed here; anything that would require running a model or a benchmark is not
stated at all.
"""


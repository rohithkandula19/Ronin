"""Render and install the pre-commit hook we drop into a checked-out repo.

The template below is written verbatim into `.git/hooks/pre-commit`. It cannot
import anything from this package: the hook runs under whatever interpreter git
hands it, in a working tree that may not have us installed. That is why it is a
string and not a module we copy.

The template is filled in with `str.format`, so every literal brace inside it is
doubled.
"""

from __future__ import annotations

import subprocess
from collections.abc import Sequence
from pathlib import Path

Check = tuple[str, Sequence[str]]

HOOK_TEMPLATE = '''#!/usr/bin/env python3
"""Generated by ronin - do not edit by hand."""
import subprocess
import sys

CHECKS = {checks}


def main() -> int:
    failures = 0
    for name, command in CHECKS:
        completed = subprocess.run(command)
        if completed.returncode != 0:
            print(f"hook: {{name}} failed", file=sys.stderr)
            failures += 1
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
'''


def render_hook(checks: Sequence[Check]) -> str:
    """Return the source of the pre-commit hook that runs `checks`."""
    body = "".join(f"    {(name, list(command))!r},\n" for name, command in checks)
    return HOOK_TEMPLATE.format(checks=f"[\n{body}]")


def install_hook(repo: Path, checks: Sequence[Check]) -> Path:
    """Write the hook into `repo` and make it executable. Returns its path."""
    target = repo / ".git" / "hooks" / "pre-commit"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_hook(checks), encoding="utf-8")
    target.chmod(0o755)
    return target


def run_checks(checks: Sequence[Check]) -> int:
    """Run `checks` in this process - used by `python -m hooks check`."""
    failures = 0
    for name, command in checks:
        if subprocess.run(command).returncode != 0:
            print(f"hook: {name} failed")
            failures += 1
    return 1 if failures else 0

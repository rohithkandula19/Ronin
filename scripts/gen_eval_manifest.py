#!/usr/bin/env python3
"""Generate ``tests/evals/manifest.toml`` from the task tree. ``--check`` in CI.

The manifest is what makes a *deleted* fixture detectable: ``load_suite`` refuses to
load when the manifest and the tree disagree, so a task someone removed cannot quietly
make the suite easier and every pass rate smaller-denominator. That check is only worth
anything if the manifest is accurate, and a hand-maintained list of 118 entries is not
going to stay accurate — the first person to add a task in a hurry forgets a stanza, the
loader starts refusing, and the fix everyone reaches for is to relax the loader.

So the file is generated, and ``--check`` fails the build when the committed copy
differs from what this script would write. The generator reads ``regression_gate`` out
of each ``task.toml`` rather than carrying its own list: the flag lives with the task it
describes, and one source of truth for "is this in the gate" is the whole point.

Usage::

    python scripts/gen_eval_manifest.py            # rewrite the manifest
    python scripts/gen_eval_manifest.py --check    # exit 1 if it is stale
"""

from __future__ import annotations

import argparse
import collections
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUITE = ROOT / "tests" / "evals"
MANIFEST = SUITE / "manifest.toml"

#: A ``task.toml`` under one of these belongs to a fixture's own contents — a task
#: whose subject is an eval suite is a real case — and is not a sibling task.
NOT_A_TASK = frozenset({"fixture", "solution", "broken", "__pycache__"})

HEADER = """\
# Flat index of tests/evals/**, generated by scripts/gen_eval_manifest.py.
# CI and the task loader read this so nothing has to walk the tree to know
# what should exist; tests/evalsuite asserts the manifest and the tree agree.
#
# Do not hand-edit: `regression_gate` comes from each task.toml, so flip the
# flag there and regenerate. `python scripts/gen_eval_manifest.py --check`
# fails the build when this file is stale.
"""


def task_dirs(suite: Path) -> list[Path]:
    """Every task directory under ``suite``, sorted by ``(category, slug)``."""
    found: list[Path] = []
    for toml in suite.rglob("task.toml"):
        relative = toml.relative_to(suite)
        if NOT_A_TASK & set(relative.parts[:-1]):
            continue
        found.append(toml.parent)
    return sorted(found, key=lambda path: path.relative_to(suite).parts)


def render(suite: Path) -> str:
    """The manifest this tree implies."""
    directories = task_dirs(suite)
    counts: collections.Counter[str] = collections.Counter()
    rows: list[tuple[str, str, bool]] = []

    for directory in directories:
        relative = directory.relative_to(suite)
        task_id = "/".join(relative.parts)
        category = relative.parts[0]
        data = tomllib.loads((directory / "task.toml").read_text(encoding="utf-8"))
        declared = data.get("id")
        if declared != task_id:
            raise SystemExit(
                f"{directory / 'task.toml'}: id is {declared!r} but its path says "
                f"{task_id!r} — a task addressed two ways cannot be reported on"
            )
        if data.get("category") != category:
            raise SystemExit(
                f"{directory / 'task.toml'}: category is {data.get('category')!r} but "
                f"it lives under {category!r}"
            )
        gate = bool(data.get("regression_gate", False))
        counts[category] += 1
        rows.append((task_id, category, gate))

    gate_total = sum(1 for _, _, gate in rows if gate)
    lines = [HEADER, f"total = {len(rows)}", f"regression_gate_total = {gate_total}", ""]
    lines.append("[counts]")
    lines.extend(f'"{category}" = {counts[category]}' for category in sorted(counts))
    for task_id, category, gate in rows:
        lines.extend(
            [
                "",
                "[[tasks]]",
                f'id = "{task_id}"',
                f'category = "{category}"',
                f"regression_gate = {str(gate).lower()}",
            ]
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the committed manifest is stale",
    )
    parser.add_argument("--suite", default=str(SUITE), help="suite root to index")
    args = parser.parse_args()

    suite = Path(args.suite).resolve()
    if not suite.is_dir():
        print(f"no such directory: {suite}", file=sys.stderr)
        return 2

    manifest = suite / "manifest.toml"
    wanted = render(suite)
    current = manifest.read_text(encoding="utf-8") if manifest.is_file() else ""

    if args.check:
        if current == wanted:
            print(f"{manifest.relative_to(ROOT)} is up to date ({len(task_dirs(suite))} tasks)")
            return 0
        print(
            f"{manifest.relative_to(ROOT)} is stale — run `python scripts/gen_eval_manifest.py`",
            file=sys.stderr,
        )
        declared = {
            line.split("=", 1)[1].strip().strip('"')
            for line in current.splitlines()
            if line.startswith("id = ")
        }
        on_disk = {
            line.split("=", 1)[1].strip().strip('"')
            for line in wanted.splitlines()
            if line.startswith("id = ")
        }
        for task_id in sorted(on_disk - declared):
            print(f"  on disk but not listed: {task_id}", file=sys.stderr)
        for task_id in sorted(declared - on_disk):
            print(f"  listed but not on disk: {task_id}", file=sys.stderr)
        return 1

    manifest.write_text(wanted, encoding="utf-8")
    print(f"wrote {manifest.relative_to(ROOT)}: {len(task_dirs(suite))} tasks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

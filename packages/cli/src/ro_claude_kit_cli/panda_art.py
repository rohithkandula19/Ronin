"""The ronin launch panda — a real panda rendered as truecolor half-block art.

The pixels live in ``panda_pixels.py`` (generated by ``tools/build_panda.py``
from a real panda image). Each character holds two vertical pixels via fg/bg
colour, so it reads as an actual panda — round ears, black eye patches, chunky
body, paws — where plain letter-ASCII just turns to noise at this size.
Shown beside the gradient RONIN wordmark.
"""
from __future__ import annotations

from rich.console import Console

try:
    from .panda_pixels import PANDA_LINES
except Exception:  # pragma: no cover - art is always shipped
    PANDA_LINES = ["  ʕ•ᴥ•ʔ  "]


def _panda_text():
    from rich.text import Text
    return Text.from_markup("\n".join(PANDA_LINES))


def _lockup():
    """The panda on the left, the RONIN gradient wordmark beside it."""
    from rich.table import Table

    from .banner import _W as _RW, _banner_text

    grid = Table.grid(padding=(0, 4))
    grid.add_column(vertical="middle")
    grid.add_column(vertical="middle")
    grid.add_row(_panda_text(), _banner_text(_RW))
    return grid


def render_panda(console: Console) -> None:
    """Print the panda + RONIN wordmark lockup."""
    console.print(_lockup())
